"""缺腿超时旁路自检：不依赖 HTTP/前端，直接跑主链路。

用法（在 backend/ 下）：python3 selfcheck_缺腿超时.py
覆盖：
  1) 进站后本批最大事件时越过最大行程秒 → 必须旁路，且不得再成对
  2) 超时后按开腿键查询 → 命中已旁路行（甲口径），valid=true
  3) 超时后再推匹配出站 → 落「超时后出站」，不得成对
  4) 扫描与出站写闸并发 → 同一进站不得旁路与行程双落
  5) 正常成对、重复进站、出站孤儿仍为 happy path
"""
import json
import os
import sys
import tempfile
import threading

os.environ.setdefault("数据目录", tempfile.mkdtemp(prefix="闸对自检-"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from app import seed  # noqa: E402
from app.db import 连接, 事务  # noqa: E402
from app.modules import 缺腿超时旁路 as 旁  # noqa: E402
from app.services import 装载, 贯验  # noqa: E402

失败 = []


def 断言(条件, 说明):
    print(("  ✓ " if 条件 else "  ✗ ") + 说明)
    if not 条件:
        失败.append(说明)


def 清空():
    conn = 连接()
    with 事务(conn):
        for t in ("刷卡点", "开腿账", "行程账", "旁路匣", "装载批次", "行程贯验"):
            conn.execute(f"DELETE FROM {t}")
    conn.close()


def 情景一():
    print("情景一：进站后本批最大事件时超最大行程秒")
    清空()
    装载.装一批(
        {
            "批次编号": "自检-超时",
            "事件": [
                {"事件编号": "s1", "卡号": "卡甲", "站点键": "站A", "方向": "进站",
                 "事件时": "2026-11-22T06:00:00Z", "处理时": "2026-11-22T06:00:01Z"},
                {"事件编号": "s9", "卡号": "卡乙", "站点键": "站C", "方向": "进站",
                 "事件时": "2026-11-22T10:00:01Z", "处理时": "2026-11-22T10:00:02Z"},
            ],
        }
    )
    conn = 连接()
    查 = 旁.查腿(conn, "腿-s1")
    行程 = conn.execute("SELECT * FROM 行程账 WHERE 进站事件编号='s1'").fetchone()
    旁路 = conn.execute(
        "SELECT * FROM 旁路匣 WHERE 开腿键='腿-s1' AND 原因='缺腿超时'"
    ).fetchall()
    conn.close()
    断言(查["是否仍在开腿表"] and 查["状态"] == "已旁路", "开腿行保留且状态已旁路")
    断言(查["旁路编号"] is not None, "旁路匣以开腿键指向该腿")
    断言(查["valid"], "只读核验 valid=true")
    断言(not 行程, "超时腿不得再成对")
    断言(len(旁路) == 1, "恰有一条缺腿超时旁路")

    print("情景一续：超时后再推匹配出站")
    装载.装一批(
        {
            "批次编号": "自检-追出",
            "事件": [
                {"事件编号": "s2", "卡号": "卡甲", "站点键": "站B", "方向": "出站",
                 "事件时": "2026-11-22T10:30:00Z", "处理时": "2026-11-22T10:30:01Z"},
            ],
        }
    )
    conn = 连接()
    查 = 旁.查腿(conn, "腿-s1")
    追出 = conn.execute(
        "SELECT * FROM 旁路匣 WHERE 开腿键='腿-s1' AND 原因='超时后出站'"
    ).fetchall()
    行程 = conn.execute("SELECT * FROM 行程账 WHERE 出站事件编号='s2'").fetchone()
    conn.close()
    断言(len(追出) == 1, "落「超时后出站」旁路")
    断言(not 行程, "超时后出站不得成对")
    断言(查["valid"] and 查["后续出站"], "只读核验含后续出站且 valid")

    print("情景一续：按开腿键查不存在的腿")
    conn = 连接()
    无 = 旁.查腿(conn, "腿-不存在")
    conn.close()
    断言(not 无["是否仍在开腿表"] and not 无["valid"], "查无 → 不命中且 valid=false")


def 情景二():
    print("情景二：扫描与出站写闸并发，不得双落")
    for 轮 in range(6):
        清空()
        装载.装一批(
            {
                "批次编号": f"自检-前置{轮}",
                "事件": [
                    {"事件编号": f"c{轮}", "卡号": "卡并", "站点键": "站A", "方向": "进站",
                     "事件时": "2026-11-22T06:00:00Z", "处理时": "2026-11-22T06:00:01Z"},
                ],
            }
        )

        def 扫描():
            装载.装一批(
                {
                    "批次编号": f"自检-并发扫{轮}",
                    "事件": [
                        {"事件编号": f"扫{轮}", "卡号": f"卡旁{轮}", "站点键": "站A",
                         "方向": "进站", "事件时": "2026-11-22T20:00:00Z",
                         "处理时": "2026-11-22T20:00:01Z"},
                    ],
                }
            )

        def 出站():
            装载.装一批(
                {
                    "批次编号": f"自检-并发出{轮}",
                    "事件": [
                        {"事件编号": f"出{轮}", "卡号": "卡并", "站点键": "站B",
                         "方向": "出站", "事件时": "2026-11-22T07:00:00Z",
                         "处理时": "2026-11-22T07:00:01Z"},
                    ],
                }
            )

        线程 = [threading.Thread(target=扫描), threading.Thread(target=出站)]
        [t.start() for t in 线程]
        [t.join() for t in 线程]

        conn = 连接()
        行程 = conn.execute(
            "SELECT * FROM 行程账 WHERE 进站事件编号=?", (f"c{轮}",)
        ).fetchone()
        超时旁 = conn.execute(
            "SELECT * FROM 旁路匣 WHERE 开腿键=? AND 原因='缺腿超时'", (f"腿-c{轮}",)
        ).fetchall()
        conn.close()
        断言(not (行程 and 超时旁), f"第{轮}轮：同一进站未同时旁路与成对")

    conn = 连接()
    结果 = 贯验.跑贯验()
    conn.close()
    断言(结果["是否通过"], "并发后贯验通过：" + 结果["说明"])


def 情景三():
    print("情景三：happy path 不回退")
    清空()
    for 名, 期望成对, 期望旁路 in (
        ("成对样例", 2, 0),
        ("缺腿超时样例", 1, 1),
        ("出站孤儿样例", 0, 1),
        ("重复进站样例", 1, 1),
    ):
        体 = json.loads(
            open(
                os.path.join(os.environ.get("夹具目录", "../fixtures"), f"{名}.json"),
                encoding="utf-8",
            ).read()
        )
        报告 = 装载.装一批(体)
        断言(
            (报告["成对"], 报告["旁路"]) == (期望成对, 期望旁路),
            f"{名}：成对{报告['成对']} 旁路{报告['旁路']}",
        )
    conn = 连接()
    结果 = 贯验.跑贯验()
    conn.close()
    断言(结果["是否通过"], "夹具串跑后贯验通过：" + 结果["说明"])


def 情景四():
    print("情景四：超时后又开新腿，再来的出站不得挂到旧旁路腿上")
