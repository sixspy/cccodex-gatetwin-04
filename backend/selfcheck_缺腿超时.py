    旧腿追出 = conn.execute(
        "SELECT COUNT(*) AS c FROM 旁路匣 WHERE 开腿键='腿-n1' AND 原因='超时后出站'"
    ).fetchone()["c"]
    conn.close()
    断言(行程 is not None and 行程["进站事件编号"] == "n3", "出站配到新腿 n3")
    断言(旧腿追出 == 1, "旧腿审计链未被新出站污染")


