import json
import sqlite3

from app.db import 连接, 事务
from app.seed import 此刻
from app.services import 时间, 配对
from app.modules.缺腿超时旁路 import NAME as _旁路模块名  # noqa: F401


def _载荷(v) -> str:
    return json.dumps(v, ensure_ascii=False)


def 装一批(体: dict) -> dict:
    """装载刷卡点：同卡进站开腿、出站成对；缺腿超时/孤儿旁路。

    口径：
    - 进站：同卡若已有在途开腿 → 旧腿旁路(重复进站)并开新腿
    - 出站：匹配同卡在途开腿 → 过成对写闸（越最大行程秒拒绝成对）。
      该卡最近已被缺腿超时旁路的腿 → 落「超时后出站」旁路，不得再成对
    - 本批最大事件时（水位）推进到每个事件时即扫缺腿超时：
      进站后本批已见最大事件时越过其最大行程秒，该腿必须旁路
    """
    批次编号 = 体.get("批次编号") or f"批-{此刻().replace(':', '').replace('-', '')}"
    事件列表 = 体.get("事件") or []
    conn = 连接()
    try:
        with 事务(conn):
            报告 = {
                "批次编号": 批次编号,
                "入流": 0,
                "开腿": 0,
                "成对": 0,
                "旁路": 0,
                "超时旁路": 0,
                "追出旁路": 0,
                "口径": "保留已旁路开腿行",
                "明细": [],
            }
            站 = {r["键"]: r["值"] for r in conn.execute("SELECT 键, 值 FROM 站规")}
            最大行程秒 = int(站.get("最大行程秒", "7200"))
            水位 = None

            def 推水位(处理时: str):
                """水位推进后立刻扫超时，使本批已见最大事件时对更早开腿生效。"""
                if not 水位:
                    return
                新旁 = 配对.扫超时(conn, 最大行程秒, 水位, 处理时)
                if not 新旁:
                    return
                报告["超时旁路"] += len(新旁)
                报告["旁路"] += len(新旁)
                for 旁 in 新旁:
                    报告["明细"].append(
                        {
                            "事件编号": 旁["事件编号"],
                            "命运": "旁路-缺腿超时",
                            "开腿键": 旁["开腿键"],
                            "旁路编号": 旁["旁路编号"],
                        }
                    )

            for ev in 事件列表:
                事件编号 = ev["事件编号"]
                卡号 = ev["卡号"]
                站点键 = ev["站点键"]
                方向 = ev["方向"]
                事件时 = ev["事件时"]
                处理时 = ev.get("处理时") or 此刻()

                if 水位 is None or 时间.解析(事件时) > 时间.解析(水位):
                    水位 = 事件时

                if conn.execute("SELECT 1 FROM 刷卡点 WHERE 事件编号=?", (事件编号,)).fetchone():
                    报告["明细"].append({"事件编号": 事件编号, "命运": "幂等跳过"})
                    continue

                站行 = conn.execute("SELECT * FROM 站点 WHERE 站点键=?", (站点键,)).fetchone()
                if not 站行:
                    conn.execute(
                        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                        ("未知站点", 卡号, 事件编号, _载荷(ev), 处理时),
                    )
                    conn.execute(
                        """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                           VALUES (?,?,?,?,?,?, '已旁路', '', ?)""",
                        (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
                    )
                    报告["旁路"] += 1
                    报告["入流"] += 1
                    报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-未知站"})
                    推水位(处理时)
                    continue

                if 方向 not in ("进站", "出站"):
                    conn.execute(
                        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                        ("方向非法", 卡号, 事件编号, _载荷(ev), 处理时),
                    )
                    conn.execute(
                        """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                           VALUES (?,?,?,?,?,?, '已旁路', '', ?)""",
                        (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
                    )
                    报告["旁路"] += 1
                    报告["入流"] += 1
                    报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-方向非法"})
                    推水位(处理时)
                    continue

                conn.execute(
                    """INSERT INTO 刷卡点(事件编号,卡号,站点键,方向,事件时,处理时,命运,行程键,批次编号)
                       VALUES (?,?,?,?,?,?, '已入流', '', ?)""",
                    (事件编号, 卡号, 站点键, 方向, 事件时, 处理时, 批次编号),
                )
                报告["入流"] += 1

                if 方向 == "进站":
                    旧 = conn.execute(
                        "SELECT * FROM 开腿账 WHERE 卡号=? AND 状态='在途'", (卡号,)
                    ).fetchone()
                    if 旧:
                        conn.execute(
                            "UPDATE 开腿账 SET 状态='已旁路', 更新处理时=? WHERE 开腿键=?",
                            (处理时, 旧["开腿键"]),
                        )
                        conn.execute(
                            "UPDATE 刷卡点 SET 命运=? WHERE 事件编号=?",
                            ("已旁路", 旧["进站事件编号"]),
                        )
                        conn.execute(
                            "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                            (
                                "重复进站",
                                卡号,
                                旧["进站事件编号"],
                                _载荷({"旧开腿": 旧["开腿键"], "新进站": 事件编号}),
                                处理时,
                            ),
                        )
                        报告["旁路"] += 1
                        报告["明细"].append(
                            {"事件编号": 旧["进站事件编号"], "命运": "旁路-重复进站"}
                        )

                    开腿键 = f"腿-{事件编号}"
                    conn.execute(
                        """INSERT INTO 开腿账(开腿键,卡号,进站事件编号,进站站点键,进站事件时,状态,更新处理时)
                           VALUES (?,?,?,?,?,'在途',?)""",
                        (开腿键, 卡号, 事件编号, 站点键, 事件时, 处理时),
                    )
                    conn.execute(
                        "UPDATE 刷卡点 SET 命运=? WHERE 事件编号=?",
                        ("已开腿", 事件编号),
                    )
                    报告["开腿"] += 1
                    报告["明细"].append({"事件编号": 事件编号, "命运": "已开腿", "开腿键": 开腿键})
                    推水位(处理时)
                    continue

                开腿 = conn.execute(
                    "SELECT * FROM 开腿账 WHERE 卡号=? AND 状态='在途' ORDER BY 进站事件时 ASC LIMIT 1",
                    (卡号,),
                ).fetchone()

                if not 开腿:
                    超时腿 = 配对.找超时腿(conn, 卡号)
                    if 超时腿:
                        conn.execute("UPDATE 刷卡点 SET 命运='已旁路' WHERE 事件编号=?", (事件编号,))
                        编号 = 配对.记追出(conn, 超时腿, 事件编号, 站点键, 事件时, 处理时)
                        报告["追出旁路"] += 1
                        报告["旁路"] += 1
                        报告["明细"].append(
                            {
                                "事件编号": 事件编号,
                                "命运": "旁路-超时后出站",
                                "开腿键": 超时腿["开腿键"],
                                "旁路编号": 编号,
                            }
                        )
                    else:
                        conn.execute("UPDATE 刷卡点 SET 命运=? WHERE 事件编号=?", ("已旁路", 事件编号))
                        conn.execute(
                            "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
                            ("出站孤儿", 卡号, 事件编号, _载荷(ev), 处理时),
                        )
                        报告["旁路"] += 1
                        报告["明细"].append({"事件编号": 事件编号, "命运": "旁路-出站孤儿"})
                    推水位(处理时)
                    continue

                try:
                    行程键 = 配对.成对写出站(
                        conn, 开腿, 事件编号, 站点键, 事件时, 处理时, 最大行程秒
                    )
                except sqlite3.IntegrityError:
                    # 唯一索引兜底：同一进站已落行程，禁止重复成对
                    行程键 = None
                if not 行程键:
                    # 写闸拒绝：腿已旁路 / 历时越界 / 已落行程，该出站不得成对
                    conn.execute("UPDATE 刷卡点 SET 命运='已旁路' WHERE 事件编号=?", (事件编号,))
                    最新腿 = conn.execute(
                        "SELECT * FROM 开腿账 WHERE 开腿键=?", (开腿["开腿键"],)
                    ).fetchone()
                    编号 = 配对.记追出(conn, 最新腿 or 开腿, 事件编号, 站点键, 事件时, 处理时)
                    报告["追出旁路"] += 1
                    报告["旁路"] += 1
                    报告["明细"].append(
                        {
                            "事件编号": 事件编号,
                            "命运": "旁路-超时后出站",
                            "开腿键": 开腿["开腿键"],
                            "旁路编号": 编号,
                        }
                    )
                else:
                    报告["成对"] += 1
                    报告["明细"].append(
                        {"事件编号": 事件编号, "命运": "已成对", "行程键": 行程键}
                    )
                推水位(处理时)

            # 同批次编号可重复灌（夹具按钮可能连点）：已存在则顺延编号，保留历史报告
            实批次 = 批次编号
            n = 1
            while conn.execute("SELECT 1 FROM 装载批次 WHERE 编号=?", (实批次,)).fetchone():
                n += 1
                实批次 = f"{批次编号}#{n}"
            报告["批次编号"] = 实批次
            conn.execute(
                "INSERT INTO 装载批次(编号, 时刻, 报告) VALUES (?,?,?)",
                (实批次, 此刻(), _载荷(报告)),
            )
        return 报告
    finally:
        conn.close()
